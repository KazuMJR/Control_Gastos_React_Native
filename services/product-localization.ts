function readableCategory(category: string) {
  return category
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

export function localizeProduct(product: RawProduct): Product {
  return {
    ...product,
    originalTitle: product.title,
    originalCategory: product.category,
    title: PRODUCT_NAMES[product.title] ?? product.title,
    category: CATEGORY_NAMES[product.category] ?? readableCategory(product.category),
  };
}

// Quita tildes y diferencias de mayúsculas para permitir búsquedas flexibles.
export function normalizeCatalogText(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase("es")
    .trim();
}

export function productMatchesSearch(product: Product, query: string) {
  const normalizedQuery = normalizeCatalogText(query);

  if (!normalizedQuery) {
    return true;
  }

  const searchableText = normalizeCatalogText(
    [
      product.title,
      product.category,
      product.brand,
      product.originalTitle,
      product.originalCategory,
    ]
      .filter(Boolean)
      .join(" ")
  );

  return normalizedQuery
    .split(/\s+/)
    .every((term) => searchableText.includes(term));
}
